import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = '../suite/artifacts/study/paper-audit/audit.json';
const audit = JSON.parse(readFileSync(resolve(here, source), 'utf8'));
const plan = JSON.parse(readFileSync(resolve(here, 'experiments.json'), 'utf8'));
const sha = file => createHash('sha256').update(readFileSync(resolve(here, file))).digest('hex');
assert.equal(audit.coverage.sourceGroups, 5120);
assert.equal(audit.copyControls.cases, 35840);
assert.equal(audit.cases, 117910);
assert.equal(audit.controlsSha256, sha('../suite/artifacts/study/paper-audit/copy-controls.jsonl.gz'));
assert.equal(plan.status, 'proposed-not-frozen');
const tex = s => String(s).replaceAll('_', '\\_').replaceAll('%', '\\%').replaceAll('&', '\\&');
const write = (name, lines) => writeFileSync(resolve(here, 'tables', name + '.tex'),
  '% Generated by generate-audit.mjs; do not edit.\n' + lines.join('\n') + '\n');
const metric = (row, name) => {
  const value = row.metrics[name]?.mean;
  return value == null ? 'n/a' : (value * 100).toFixed(1);
};
write('copy-controls', audit.copyControls.summary.map(r =>
  `${tex(r.key)} & ${r.cases.toLocaleString('en-US')} & ${metric(r, 'success')} & ${metric(r, 'partF1')} & ${
    metric(r, r.key.startsWith('complete') ? 'additionF1' : r.key.startsWith('repair') ? 'localizationF1' : 'editTargetSuccess')} \\\\`));
write('catalog-coverage', audit.coverage.partTypes.map(r =>
  `${r.partId} & ${r.name} & ${r.instances.toLocaleString('en-US')} & ${r.objects.toLocaleString('en-US')} \\\\`));
const defs = [
  ['parts', 'Part recognition', '2 isolated RGB views', 'Type, color, stud count', 'All three fields correct'],
  ['relations', 'Relations (2)', 'Symbolic structure + two IDs', 'Connection, above, studs, distance', 'All four fields correct'],
  ['reconstruct', 'Reconstruction', 'Reference + BOM', 'Full structure', 'Condition-specific match + legality'],
  ['generate', 'Generation', 'Six public constraints', 'Any satisfying structure', 'All constraints + legality'],
  ['complete', 'Completion', 'Current prefix + reference + BOM', 'Full structure', 'Match + preserved prefix'],
  ['edit', 'Editing (3)', 'Current structure + operation', 'Full edited structure', 'Exact edit + protected preservation'],
  ['plan', 'Planning (2)', 'Target structure + direction', 'Permutation of all IDs', 'Complete executable order'],
  ['repair', 'Repair (3)', 'Current + reference + BOM', 'Structure + faulty current IDs', 'Match + preservation + localization'],
];
write('task-contract', defs.map(([kind, label, input, output, criterion]) => {
  const row = audit.taskCounts.find(r => r.kind === kind);
  assert.ok(row);
  return `${label} & ${input} & ${output} & ${criterion} & ${row.cases.toLocaleString('en-US')} \\\\`;
}));
let blanks = 0;
for (const table of plan.tables) {
  assert.match(table.id, /^[a-z]+$/);
  for (const row of table.rows) {
    assert.equal(row.values.length, table.columns.length);
    assert.ok(row.values.every(v => v === null), 'Prospective tables cannot silently contain claimed measurements');
    blanks += row.values.length;
  }
  write('planned-' + table.id, [
    '\\renewcommand{\\arraystretch}{1.25}',
    '\\begin{tabular*}{\\textwidth}{@{}l@{\\extracolsep{\\fill}}' + 'c'.repeat(table.columns.length) + '@{}}',
    '\\toprule',
    ['Method / condition', ...table.columns].map(tex).join(' & ') + ' \\\\',
    '\\midrule',
    ...table.rows.map(row => [tex(row.label), ...row.values.map(() => '\\unmeasured')].join(' & ') + ' \\\\'),
    '\\bottomrule', '\\end{tabular*}',
  ]);
}
write('planned-additional', plan.tables.filter(t => ['feedback', 'representation', 'ambiguity', 'planning', 'crossbench'].includes(t.id))
  .flatMap(table => [
    `\\subsection{${tex(table.title)}}`,
    tex(table.design),
    '\\begin{table}[H]\\centering\\small',
    `\\input{tables/planned-${table.id}.tex}`,
    `\\caption{\\textbf{Unmeasured.} ${tex(table.title)}. Blank cells are unrun results, not zeros.}`,
    '\\end{table}',
  ]));
writeFileSync(resolve(here, 'audit-evidence.json'), JSON.stringify({
  scope: 'Full source inventory and public-input copy controls; planned tables have no measured results.',
  audit: { path: source, sha256: sha(source) }, experimentPlanSha256: sha('experiments.json'),
  generatorSha256: sha('generate-audit.mjs'),
  plannedTables: plan.tables.length, unmeasuredCells: blanks,
  tables: ['copy-controls', 'catalog-coverage', 'task-contract', ...plan.tables.map(t => 'planned-' + t.id)],
}, null, 2) + '\n');
console.log(JSON.stringify({ actualTypes: audit.coverage.assembledTypes, plannedTables: plan.tables.length, blanks,
  copy: audit.copyControls.summary.map(r => ({ task: r.key, success: metric(r, 'success'), partF1: metric(r, 'partF1') })) }));
